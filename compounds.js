const COMPOUND_BY_ID = new Map(COMPOUNDS.map((c) => [c.id, c]));

/* smallest whole-number signature: {Fe:2,O:3} -> "Fe2O3" */
function compoundSignature(atoms) {
  const syms = Object.keys(atoms).filter((s) => atoms[s] > 0).sort();
  const g = syms.reduce((a, s) => CHEM.gcd(a, atoms[s]), 0) || 1;
  return syms.map((s) => `${s}${atoms[s] / g}`).join('');
}

const COMPOUND_BY_SIG = new Map(
  COMPOUNDS.filter((c) => c.atoms).map((c) => [compoundSignature(c.atoms), c])
);

const ALLOY_BY_METALS = new Map(
  COMPOUNDS.filter((c) => c.kind === 'alloy').map((c) => [[...c.metals].sort().join('-'), c])
);

/* compound formulas that share the same element set at other ratios,
   used to explain ambiguous mixtures without inventing a product */
function alternativeCompounds(atoms, excludeId) {
  const set = Object.keys(atoms).filter((s) => atoms[s] > 0).sort().join('');
  return COMPOUNDS.filter((c) => {
    if (!c.atoms || c.id === excludeId) return false;
    return Object.keys(c.atoms).sort().join('') === set;
  });
}

/* relative formula mass from the shared element masses */
function compoundMass(c) {
  if (!c.atoms) return null;
  let total = 0;
  Object.entries(c.atoms).forEach(([sym, n]) => {
    const row = ELEMENTS.find((e) => e[1] === sym);
    if (!row) return;
    total += parseFloat(String(row[6]).replace(/[[\]]/g, '')) * n;
  });
  return total ? total.toFixed(2) : null;
}
